"""End-to-end dealership workflow through the HTTP API (fixture data, sandbox channel)."""
from __future__ import annotations

from tests.conftest import SAMPLE_CSV, login, run_worker


def test_inventory_to_published_listing_via_api(world, client):
    a = world["a"].id
    h = login(client, "owner@alpha.test")
    base = f"/api/clients/{a}"
    r = client.put(f"{base}/listing-settings", headers=h, json={
        "contact": {"dealership_name": "Alpha Auto", "phone": "(281) 555-0199", "email": "sales@alpha.test", "website": "", "address": "123 Main St"},
        "enabled_channels": ["facebook_marketplace", "sandbox"]})
    assert r.status_code == 200
    r = client.post(f"{base}/imports/upload", headers=h, files={"file": ("inv.csv", SAMPLE_CSV.encode(), "text/csv")})
    assert r.status_code == 201 and r.json()["counts"]["created"] == 3
    run_worker()  # drafts generated by the background worker
    listings = client.get(f"{base}/listings?status=awaiting_approval", headers=h).json()["items"]
    assert len(listings) == 3
    ids = [x["id"] for x in listings]
    pv = client.post(f"{base}/listings/batch/preview", headers=h, json={"listing_ids": ids}).json()
    r = client.post(f"{base}/listings/batch/approve", headers=h, json={"listing_ids": ids, "expected_count": pv["eligible_count"],
                                                                         "confirm": True, "acknowledge_all_warnings": True})
    assert r.status_code == 200 and len(r.json()["approved"]) == 3, r.text
    detail = client.get(f"{base}/listings/{ids[0]}", headers=h).json()
    by_channel = {p["channel"]: p for p in detail["publications"]}
    assert by_channel["facebook_marketplace"]["status"] == "manual_required"
    assert by_channel["sandbox"]["status"] == "ready_to_publish"
    pkg = client.get(f"{base}/publications/{by_channel['facebook_marketplace']['id']}", headers=h).json()
    assert pkg["package"]["copy"]["en"]["title"] and pkg["package"]["checklist"]
    r = client.post(f"{base}/publications/{by_channel['facebook_marketplace']['id']}/confirm-manual", headers=h,
                    json={"url": "https://www.facebook.com/marketplace/item/99887766554433/", "attested": True})
    assert r.status_code == 200 and r.json()["confirmation_type"] == "manual_attested"
    assert client.post(f"{base}/publications/{by_channel['sandbox']['id']}/publish", headers=h).status_code == 202
    run_worker()
    report = client.get(f"{base}/reports/summary", headers=h).json()
    assert report["publishing"]["published_confirmed_manually"] == 1
    assert report["publishing"]["published_confirmed_via_api"] == 0  # sandbox is not a real API integration
    assert report["listings"]["approved_in_period"] == 3 and report["inventory"]["imported_in_period"] == 3
    csv = client.get(f"{base}/exports/listings.csv?lang=es", headers=h)
    assert csv.status_code == 200 and "millas" in csv.text
    audit = client.get(f"{base}/audit", headers=h).json()
    assert {"inventory.imported", "listing.generated", "listing.approved", "publication.manual_confirmed"} <= {x["action"] for x in audit}
    assert client.get("/api/health").json()["database"] == "ok"
